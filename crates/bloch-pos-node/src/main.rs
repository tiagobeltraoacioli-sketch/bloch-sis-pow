/// `submit-tx --to <host:port> --spend <txid-hex>:<vout> --pubkey <hex>
///  --pay <script-hash-hex>:<sat> [--signature <hex>] [--tx-bytes n] [--tip n]`
///
/// Builds one `Transfer` and hands it to a node, which gossips it onward.
/// Transfer is the only variant this emits on purpose: `Deposit` and
/// `Delegate` describe validator-set changes that a devnet's genesis set does
/// not need and that would want key material to be meaningful, and evidence
/// cannot travel this way at all — its canonical encoding is one-way (see
/// `PosTransaction::from_canonical_bytes`).
///
/// # Why the flags changed shape
///
/// This used to read `--inputs n --tx-bytes n --tip n`: three numbers that
/// described a transfer's *cost* and named no coin, no recipient and no
/// amount, because that was all the variant carried. A transfer now moves
/// value, so it needs the outpoints it spends, the key that unlocks them, and
/// the outputs it creates.
///
/// # This tool does not hold keys and does not sign
///
/// With no `--signature` it prints the transfer's signing root and stops:
/// that digest is what an external signer — the wallet, an HSM, an air-gapped
/// machine — takes, and the resulting signature comes back in on
/// `--signature`. A devnet convenience that generated a keypair here would be
/// a keypair on an operator's shell history, and this crate has no business
/// creating spending keys at all.
fn submit_tx(args: &[String]) {
    let Some(to) = arg_value(args, "--to") else {
        eprintln!("submit-tx: --to <host:port> is required");
        exit(2);
    };
    let num = |name: &str, default: u128| -> u128 {
        arg_value(args, name)
            .and_then(|s| s.parse().ok())
            .unwrap_or(default)
    };
    let bail = |m: String| -> ! {
        eprintln!("submit-tx: {m}");
        exit(2)
    };

    // --spend <txid-hex>:<vout>, repeatable.
    let mut inputs = Vec::new();
    let pubkey = match arg_value(args, "--pubkey").as_deref().map(codec::unhex) {
        Some(Ok(k)) => k,
        Some(Err(e)) => bail(format!("--pubkey: {e}")),
        None => bail("--pubkey <hex> is required".into()),
    };
    for (i, a) in args.iter().enumerate() {
        if a != "--spend" {
            continue;
        }
        let Some(spec) = args.get(i + 1) else {
            bail("--spend needs <txid-hex>:<vout>".into())
        };
        let Some((txid_hex, vout)) = spec.rsplit_once(':') else {
            bail(format!("--spend {spec}: expected <txid-hex>:<vout>"))
        };
        let txid = match codec::unhex(txid_hex) {
            Ok(b) if b.len() == 32 => {
                let mut a = [0u8; 32];
                a.copy_from_slice(&b);
                a
            }
            Ok(b) => bail(format!("--spend: txid is {} bytes, expected 32", b.len())),
            Err(e) => bail(format!("--spend: {e}")),
        };
        let Ok(vout) = vout.parse::<u32>() else {
            bail(format!("--spend: bad vout {vout}"))
        };
        inputs.push(bloch_pos_committee::transition::TransferInput {
            txid,
            vout,
            pubkey: pubkey.clone(),
            // Filled in below once the signing root is known; a signature can
            // never cover itself.
            signature: Vec::new(),
        });
    }
    if inputs.is_empty() {
        bail("at least one --spend <txid-hex>:<vout> is required".into());
    }

    // --pay <script-hash-hex>:<sat>, repeatable and ordered: the position IS
    // the vout, so the order the flags are given in is consensus-visible.
    let mut outputs = Vec::new();
    for (i, a) in args.iter().enumerate() {
        if a != "--pay" {
            continue;
        }
        let Some(spec) = args.get(i + 1) else {
            bail("--pay needs <script-hash-hex>:<sat>".into())
        };
        let Some((sh_hex, value)) = spec.rsplit_once(':') else {
            bail(format!("--pay {spec}: expected <script-hash-hex>:<sat>"))
        };
        let script_hash = match codec::unhex(sh_hex) {
            Ok(b) if b.len() == 32 => {
                let mut a = [0u8; 32];
                a.copy_from_slice(&b);
                a
            }
            Ok(b) => bail(format!(
                "--pay: script hash is {} bytes, expected 32",
                b.len()
            )),
            Err(e) => bail(format!("--pay: {e}")),
        };
        let Ok(value) = value.parse::<u64>() else {
            bail(format!("--pay: bad value {value}"))
        };
        outputs.push(bloch_pos_committee::transition::TransferOutput { value, script_hash });
    }

    // `tx_bytes` is INSIDE the signing root, so it has to be fixed before the
    // root is printed and must not move afterwards — raising it to fit the
    // encoding after signing would silently invalidate the signature that was
    // produced over the smaller value. The default assumes one hybrid
    // signature per input (`HYBRID_SIG_BYTES`) plus a generous envelope; an
    // exact figure is what `--tx-bytes` is for.
    let n_inputs = inputs.len() as u64;
    let default_bytes = 1_024
        + n_inputs * (bloch_pos_committee::fee_market::HYBRID_SIG_BYTES + pubkey.len() as u64 + 64);
    let mut tx = bloch_pos_committee::transition::PosTransaction::Transfer {
        inputs,
        outputs,
        tx_bytes: num("--tx-bytes", default_bytes as u128) as u64,
        tip_millisat_per_gas: num("--tip", 1_000),
    };

    let Some(sig_hex) = arg_value(args, "--signature") else {
        // No signature: print what has to be signed and stop. The root does
        // not depend on the signatures — which is exactly why it can be shown
        // before they exist — but it DOES depend on every other field, so the
        // same flags must be repeated verbatim on the signed run.
        println!("{}", codec::hex(&tx.spend_signing_root()));
        eprintln!(
            "submit-tx: no --signature given; the line above is the signing root.\n\
             Sign it with the key whose SHA3-256 the spent outputs commit to, then\n\
             re-run with the SAME flags plus --signature <hex>. Changing any flag\n\
             (including --tx-bytes and --tip) changes the root and voids the\n\
             signature. Nothing was sent."
        );
        exit(0);
    };
    let signature = match codec::unhex(&sig_hex) {
        Ok(s) => s,
        Err(e) => bail(format!("--signature: {e}")),
    };
    if let bloch_pos_committee::transition::PosTransaction::Transfer { inputs, .. } = &mut tx {
        for i in inputs.iter_mut() {
            i.signature = signature.clone();
        }
    }
    // Consensus refuses a declared size below the encoding
    // (`TransferReject::UnderdeclaredSize`). Report it instead of "fixing" it:
    // the fix is to re-sign at a larger --tx-bytes, and only the key holder
    // can do that.
    let encoded = tx.canonical_bytes().len() as u64;
    if let bloch_pos_committee::transition::PosTransaction::Transfer { tx_bytes, .. } = &tx {
        if *tx_bytes < encoded {
            bail(format!(
                "--tx-bytes {tx_bytes} is below this transaction's {encoded}-byte encoding; \
                 a node would refuse it. Re-run the unsigned step with \
                 --tx-bytes {encoded} (or more) and sign that root instead."
            ));
        }
    }
    let bytes = tx.canonical_bytes();
    match bloch_pos_node_net_send(&to, &bytes) {
        Ok(()) => println!(
            "submitted {} bytes to {to} — it lands in a block or it does not; \
             this transport does not acknowledge",
            bytes.len()
        ),
        Err(e) => {
            eprintln!("submit-tx: {e}");
            exit(1);
        }
    }
}

fn bloch_pos_node_net_send(addr: &str, bytes: &[u8]) -> std::io::Result<()> {
    net::send_transaction(addr, bytes)
}

fn arg_value(args: &[String], name: &str) -> Option<String> {
    args.iter()
        .position(|a| a == name)
        .and_then(|i| args.get(i + 1))
        .cloned()
}

/// Which genesis-binding rule to stamp into a manifest this command emits.
///
/// Default is [`genesis::ManifestFormat::V1Unbound`] — the rule the live
/// Genesis-4 chain launched under. `--bind-genesis` selects the bound rule
/// (audit C5-genesis-header): the genesis header then carries the genesis
/// state root and a carryover-seeded RANDAO mix, so the block id at height 0
/// is a function of the ledger instead of a constant every network shares.
///
/// It is a flag and not a default because a manifest emitted with it has a
/// DIFFERENT `genesis_id` from the one the fleet runs. That is a new network,
/// not an upgrade: no node can adopt it without relaunching from its block 0.
/// Publishing such a manifest is the founder's decision.
fn manifest_format(args: &[String]) -> genesis::ManifestFormat {
    if args.iter().any(|a| a == "--bind-genesis") {
        genesis::ManifestFormat::V2Bound
    } else {
        genesis::ManifestFormat::V1Unbound
    }
}

/// `keygen-public --dir <dir>` — one TSV row of a keystore's PUBLIC halves.
///
/// The carry-out half of the ceremony. An air-gapped machine holds the
/// keystores forever; what leaves it is this row per validator, and nothing
/// else. Reads the keystore and prints index, hybrid public key, and the
/// RANDAO commitment — the head of the reveal chain, which is a commitment
/// precisely so the seed behind it can stay on the machine.
///
/// The three columns it cannot know are left empty rather than defaulted:
/// `stake_sat`, `withdrawal_credentials` and `commission_bps` are decisions,
/// not derivations, and a genesis where nobody chose them is a genesis
/// somebody will have to explain later.
///
/// Nothing here can print a secret: `Keystore`'s secret field is private and
/// implements no `Debug`, so there is no path from this function to the key.
fn keygen_public(args: &[String]) {
    let Some(dir) = arg_value(args, "--dir") else {
        eprintln!("keygen-public: --dir is required");
        exit(2);
    };
    match keys::Keystore::load(&PathBuf::from(&dir)) {
        Ok(ks) => {
            let commitment =
                bloch_pos_committee::beacon::RandaoChain::generate(ks.randao_seed).commitment();
            println!(
                "{}\t{}\t{}\t\t\t",
                ks.index,
                hex_lower(&ks.pubkey),
                hex_lower(&commitment)
            );
        }
        Err(e) => {
            eprintln!("keygen-public: cannot read {dir}: {e}");
            exit(1);
        }
    }
}

fn hex_lower(b: &[u8]) -> String {
    let mut s = String::with_capacity(b.len() * 2);
    for byte in b {
        s.push_str(&format!("{byte:02x}"));
    }
    s
}

/// `keys seal | inspect` — the keystore migration family (audit round 3,
/// flag-day prerequisite).
///
/// Passphrase sourcing, in order: `--passphrase-file <path>` (mode-checked
/// 0600), else the controlling terminal with echo off. There is deliberately
/// no `--passphrase <text>`: argv is world-readable in `ps`, lands in shell
/// history and in every jump host's audit log. The environment variable the
/// node itself reads (`BLOCH_KEYSTORE_PASSPHRASE`) is honoured here too, with
/// the same loud warning `Unlock::from_env` prints, so an operator who has
/// already wired `LoadCredential=` can seal with exactly the passphrase the
/// unit will use.
fn keys_cmd(args: &[String]) {
    match args.first().map(String::as_str) {
        Some("seal") => keys_seal(&args[1..]),
        Some("inspect") => keys_inspect(&args[1..]),
        _ => {
            eprintln!("keys: expected `seal` or `inspect` (see --help)");
            exit(2);
        }
    }
}

fn keys_seal(args: &[String]) {
    let Some(dir) = arg_value(args, "--dir") else {
        eprintln!("keys seal: --dir <datadir> is required");
        exit(2);
    };
    if arg_value(args, "--passphrase").is_some() {
        eprintln!(
            "keys seal: --passphrase <text> is not accepted (a command line is visible in `ps` \
             and shell history). Use --passphrase-file <0600 file> or type it at the prompt."
        );
        exit(2);
    }
    let pass = if let Some(f) = arg_value(args, "--passphrase-file") {
        match keys::read_passphrase_file(&PathBuf::from(&f)) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("keys seal: {e}");
                exit(1);
            }
        }
    } else if let Some(f) = std::env::var_os("BLOCH_KEYSTORE_PASSPHRASE_FILE") {
        match keys::read_passphrase_file(&PathBuf::from(&f)) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("keys seal: BLOCH_KEYSTORE_PASSPHRASE_FILE: {e}");
                exit(1);
            }
        }
    } else {
        let first = match keys::read_passphrase_from_tty("New keystore passphrase: ") {
            Ok(p) => p,
            Err(e) => {
                eprintln!("keys seal: {e}");
                exit(1);
            }
        };
        let again = match keys::read_passphrase_from_tty("Repeat passphrase: ") {
            Ok(p) => p,
            Err(e) => {
                eprintln!("keys seal: {e}");
                exit(1);
            }
        };
        if first.as_str() != again.as_str() {
            eprintln!("keys seal: passphrases do not match; nothing was written");
            exit(1);
        }
        first
    };
    match keys::Keystore::seal_in_place(&PathBuf::from(&dir), &pass, keys::KdfParams::PRODUCTION) {
        Ok(r) => {
            // Public information only — never a secret byte.
            println!(
                "sealed {dir}/validator.key: validator {}, pubkey sha3 {}, Argon2id m={} KiB t={} p={}, \
                 {} plaintext bytes zero-filled (best effort). Set BLOCH_KEYSTORE_PASSPHRASE_FILE \
                 in the unit before the next start; the plaintext opt-in no longer opens this file.",
                r.index,
                codec::hex8(&r.pubkey_sha3),
                r.kdf.m_cost,
                r.kdf.t_cost,
                r.kdf.p_cost,
                r.plaintext_bytes_overwritten
            );
        }
        Err(e) => {
            eprintln!("keys seal failed: {e}");
            exit(1);
        }
    }
}

fn keys_inspect(args: &[String]) {
    let Some(dir) = arg_value(args, "--dir") else {
        eprintln!("keys inspect: --dir <datadir> is required");
        exit(2);
    };
    let dir = PathBuf::from(&dir);
    match keys::Keystore::inspect(&dir) {
        Ok(info) => {
            println!("file      : {}", dir.join("validator.key").display());
            println!("format    : {}", info.format);
            println!("index     : {}", info.index);
            println!("pubkey    : sha3-256 {} ({} bytes)", codec::hex8(&info.pubkey_sha3), info.pubkey_len);
            match info.kdf {
                Some(k) => println!("kdf       : Argon2id m={} KiB t={} p={}", k.m_cost, k.t_cost, k.p_cost),
                None => println!("kdf       : none (PLAINTEXT — run `bloch-pos keys seal`)"),
            }
            if let Some(m) = info.mode {
                println!(
                    "mode      : {m:04o}{}",
                    if m & 0o077 != 0 { "  <-- readable by group/others: the loader will refuse it" } else { "" }
                );
            }
            println!("length    : {} bytes", info.file_len);
        }
        Err(e) => {
            eprintln!("keys inspect: cannot read {}: {e}", dir.display());
            exit(1);
        }
    }
    // Whether a node is running over the dir, via the same lock the node
    // takes. Taking and releasing it here is harmless: without a running node
    // nothing else contends for it, and with one it is refused.
    match store::DirLock::acquire(&dir) {
        Ok(lock) => println!("data dir  : lock free ({})", lock.path().display()),
        Err(e) if e.kind() == std::io::ErrorKind::AddrInUse => {
            println!("data dir  : IN USE by a running node — `keys seal` will refuse until it stops")
        }
        Err(e) => println!("data dir  : lock check failed ({e})"),
    }
}

fn keygen(args: &[String]) {
    let Some(dir) = arg_value(args, "--dir") else {
        eprintln!("keygen: --dir is required");
        exit(2);
    };
    let Some(index) = arg_value(args, "--index").and_then(|s| s.parse::<u32>().ok()) else {
        eprintln!("keygen: --index <u32> is required");
        exit(2);
    };
    match keys::Keystore::generate(&PathBuf::from(&dir), index) {
        Ok(ks) => {
            use sha3::{Digest, Sha3_256};
            let pkh: [u8; 32] = Sha3_256::digest(&ks.pubkey).into();
            // Public information only — never a secret byte.
            println!(
                "wrote {dir}/validator.key (devnet, throwaway): validator {index}, \
                 pubkey sha3 {}, randao commitment {}",
                codec::hex8(&pkh),
                codec::hex8(
                    &bloch_pos_committee::beacon::RandaoChain::generate(ks.randao_seed)
                        .commitment()
                )
            );
        }
        Err(e) => {
            eprintln!("keygen failed: {e}");
            exit(1);
        }
    }
}

/// `genesis-mainnet --cohort <cohort.tsv> --out <file> [--start-in <secs>]
/// [--bind-genesis]`
///
/// Assemble the mainnet manifest from the ceremony's **public halves only**.
///
/// The devnet `genesis` command reads keystores, which is exactly what must
/// never leave the air-gapped machine. This reads the one file the ceremony is
/// designed to carry out: index, public key, RANDAO commitment, and the three
/// columns a human decided. No secret can reach this path because none is in
/// its input.
///
/// The carryover commitment is built from the constants the terminal snapshot
/// pinned, not from the snapshot file: assembling a manifest is a statement
/// about which balance set this chain opens with, and the file itself is
/// checked later, at node start, against exactly these four fields.
fn genesis_mainnet(args: &[String]) {
    use bloch_pos_committee::tokenomics_v4 as t;

    let Some(cohort_path) = arg_value(args, "--cohort") else {
        eprintln!("genesis-mainnet: --cohort <cohort.tsv> is required");
        exit(2);
    };
    let Some(out) = arg_value(args, "--out") else {
        eprintln!("genesis-mainnet: --out <file> is required");
        exit(2);
    };
    let start_in: u64 = arg_value(args, "--start-in")
        .and_then(|s| s.parse().ok())
        .unwrap_or(900);

    let text = match std::fs::read_to_string(&cohort_path) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("genesis-mainnet: cannot read {cohort_path}: {e}");
            exit(1);
        }
    };

    let hex = |s: &str, what: &str, row: usize| -> Vec<u8> {
        if s.len() % 2 != 0 || !s.bytes().all(|b| b.is_ascii_hexdigit()) {
            eprintln!("genesis-mainnet: row {row}: {what} is not hex");
            exit(1);
        }
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    };

    let mut validators = Vec::new();
    for (n, line) in text.lines().enumerate().skip(1) {
        if line.trim().is_empty() {
            continue;
        }
        let c: Vec<&str> = line.split('\t').collect();
        if c.len() < 6 {
            eprintln!(
                "genesis-mainnet: row {n}: expected 6 columns, found {}",
                c.len()
            );
            exit(1);
        }
        // Every field is refused rather than defaulted. A validator set is the
        // one artifact nobody can correct later — once a chain runs from it,
        // whatever it said is what happened.
        let bad = |what: &str| -> ! {
            eprintln!("genesis-mainnet: row {n}: {what}");
            exit(1)
        };
        let index: u32 = c[0]
            .trim()
            .parse()
            .unwrap_or_else(|_| bad("index is not a number"));
        let pubkey = hex(c[1].trim(), "pubkey", n);
        let randao = hex(c[2].trim(), "randao_commitment", n);
        if randao.len() != 32 {
            bad("randao_commitment is not 32 bytes");
        }
        let stake_sat: u128 = c[3].trim().parse().unwrap_or_else(|_| bad("stake_sat is empty or not a number — it is a decision, and the ceremony leaves it blank on purpose"));
        if stake_sat < t::SAT_PER_BLOCH * 25_000 {
            bad("stake_sat is below the 25,000 BLOCH minimum deposit");
        }
        let wc = hex(c[4].trim(), "withdrawal_credentials", n);
        if wc.len() != 32 {
            bad("withdrawal_credentials is not 32 bytes");
        }
        let commission_bps: u128 = c[5]
            .trim()
            .parse()
            .unwrap_or_else(|_| bad("commission_bps is empty or not a number"));

        let mut rc = [0u8; 32];
        rc.copy_from_slice(&randao);
        validators.push(genesis::ManifestValidator {
            index,
            stake_sat,
            randao_commitment: rc,
            pubkey,
            withdrawal_credentials: wc,
            commission_bps,
        });
    }
    if validators.is_empty() {
        eprintln!("genesis-mainnet: cohort has no validators");
        exit(1);
    }

    // The five vested buckets, from the constants. Script hashes are the
    // founder's carryover address under the same zero-extension rule the
    // carryover uses — one ownership convention on the chain, not two.
    let alloc = |purpose: u8, bloch: u128, unlock_epoch: u64| genesis::GenesisAllocation {
        purpose,
        script_hash: {
            let mut h = [0u8; 32];
            h[..20].copy_from_slice(&t::FOUNDER_WITHDRAWAL_H160);
            h
        },
        amount_sat: bloch * t::SAT_PER_BLOCH,
        unlock_epoch,
    };
    use genesis::alloc_purpose as ap;
    let allocations = vec![
        alloc(ap::FOUNDER, t::FOUNDER_BLOCH, 0),
        alloc(ap::VC, t::VC_BLOCH, 0),
        alloc(ap::TEAM, t::TEAM_BLOCH, 0),
        alloc(ap::MARKETING, t::MARKETING_BLOCH, 0),
        alloc(ap::LIQUIDITY, t::LIQUIDITY_BLOCH, 0),
    ];

    let cohort: Vec<u32> = validators.iter().map(|v| v.index).collect();
    let manifest = genesis::Manifest {
        genesis_time_ms: std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_millis() as u64
            + start_in * 1000,
        slot_ms: 30_000,
        validators,
        cohort,
        // The entries are NOT here, and that is the design: they are ingested
        // at node start from the snapshot file and checked against the four
        // fields below. A manifest is the artifact every node hashes to decide
        // which network it joined; a 54 MB balance set does not belong in it.
        carryover_entries: Vec::new(),
        format: manifest_format(args),
        pre_state_root: std::sync::OnceLock::new(),
        carryover: Some(genesis::CarryoverCommitment {
            digest: t::CARRYOVER_MEASURED_FILE_SHA3_256,
            set_root: t::CARRYOVER_MEASURED_ROOT,
            entry_count: t::CARRYOVER_MEASURED_UTXOS,
            total_sat: t::CARRYOVER_TOTAL_BLOCH * t::SAT_PER_BLOCH,
        }),
        allocations,
    };

    // The check that makes this a claim rather than an assertion.
    if let Err(e) = manifest.check_supply() {
        eprintln!("genesis-mainnet: {e}");
        exit(1);
    }
    // The exhaustive rule, ENFORCED (2026-09-04). This was `WARNING (not
    // fatal)` for one release, on the argument that Genesis-4 mainnet bonds
    // its launch cohort outside `GENESIS_ISSUED_SAT` and a hard check would
    // stop the tool regenerating the artifact the live chain runs from. The
    // argument was right about the constraint and wrong about the remedy: a
    // warning makes the omission a decision nobody makes, which is how the
    // first unfunded cohort shipped. `check_bonds_are_funded` now compares
    // against a named, frozen ceiling, so committed history regenerates and
    // anything that bonds MORE from nothing exits non-zero here.
    if let Err(e) = manifest.check_bonds_are_funded() {
        eprintln!("genesis-mainnet: {e}");
        exit(1);
    }

    let bytes = manifest.encode();
    if let Err(e) = std::fs::write(&out, &bytes) {
        eprintln!("genesis-mainnet: cannot write {out}: {e}");
        exit(1);
    }
    use sha3::{Digest, Sha3_256};
    let digest: [u8; 32] = Sha3_256::digest(&bytes).into();
    println!(
        "wrote {out}\n  validators : {}\n  carryover  : {} BLOCH ({} outputs)\n  allocations: {} buckets\n  issues     : {} BLOCH at genesis\n  bonds      : {} BLOCH to the launch cohort (unfunded)\n  holds      : {} BLOCH at slot 0\n  digest     : {}",
        manifest.validators.len(),
        t::CARRYOVER_TOTAL_BLOCH,
        t::CARRYOVER_MEASURED_UTXOS,
        manifest.allocations.len(),
        manifest.genesis_issued_sat() / t::SAT_PER_BLOCH,
        manifest.genesis_bonded_sat() / t::SAT_PER_BLOCH,
        manifest.genesis_accounted_sat() / t::SAT_PER_BLOCH,
        hex_lower(&digest),
    );
}

fn genesis_cmd(args: &[String]) {
    let Some(keys_csv) = arg_value(args, "--keys") else {
        eprintln!("genesis: --keys <dir1,dir2,...> is required");
        exit(2);
    };
    let Some(out) = arg_value(args, "--out") else {
        eprintln!("genesis: --out <file> is required");
        exit(2);
    };
    let slot_ms: u64 = arg_value(args, "--slot-ms")
        .and_then(|s| s.parse().ok())
        .unwrap_or(SLOT_DURATION_SECS * 1000);
    let start_in: u64 = arg_value(args, "--start-in")
        .and_then(|s| s.parse().ok())
        .unwrap_or(5);

    let mut validators = Vec::new();
    for (i, dir) in keys_csv.split(',').enumerate() {
        let ks = match keys::Keystore::load(&PathBuf::from(dir)) {
            Ok(k) => k,
            Err(e) => {
                eprintln!("genesis: cannot load keystore {dir}: {e}");
                exit(1);
            }
        };
        if ks.index != i as u32 {
            eprintln!(
                "genesis: keystore {dir} carries index {} but sits at position {i}; \
                 indexes must be dense from 0 in --keys order",
                ks.index
            );
            exit(1);
        }
        // Uneven stakes (1x/2x/3x of 200k BLCH) so stake weighting is
        // load-bearing in every devnet run — same pattern the e2e test uses.
        let stake_sat: u128 = (i as u128 % 3 + 1) * 200_000 * SAT_PER_BLOCH;
        validators.push(genesis::ManifestValidator {
            index: ks.index,
            stake_sat,
            randao_commitment: bloch_pos_committee::beacon::RandaoChain::generate(ks.randao_seed)
                .commitment(),
            pubkey: ks.pubkey.clone(),
            withdrawal_credentials: Vec::new(),
            // Devnet: no delegation, so the rate is committed as zero. It is
            // written here rather than defaulted, because the day a devnet
            // grows delegators this line is where someone must choose.
            commission_bps: 0,
        });
    }
    let manifest = genesis::Manifest {
        genesis_time_ms: std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_millis() as u64
            + start_in * 1000,
        slot_ms,
        validators,
        cohort: Vec::new(),
        // `genesis` builds devnet manifests: no carried balances, no vested
        // allocations. The mainnet manifest is assembled by a separate path
        // that takes the signed Genesis-3 snapshot as input, because its
        // inputs come from a ceremony and not from a command line.
        carryover: None,
        allocations: Vec::new(),
        carryover_entries: Vec::new(),
        format: manifest_format(args),
        pre_state_root: std::sync::OnceLock::new(),
    };
    if let Err(e) = manifest.check_supply() {
        eprintln!("genesis: {e}");
        exit(1);
    }
    let bytes = manifest.encode();
    if let Err(e) = std::fs::write(&out, &bytes) {
        eprintln!("genesis: cannot write {out}: {e}");
        exit(1);
    }
    use sha3::{Digest, Sha3_256};
    let digest: [u8; 32] = Sha3_256::digest(&bytes).into();
    println!(
        "wrote {out}: {} validators, slot {} ms, genesis block {}, digest {}",
        manifest.validators.len(),
        slot_ms,
        codec::hex8(manifest.genesis_id().as_bytes()),
        codec::hex32(&digest)
    );
}

/// The default libp2p listen address, used when a plan runs a swarm and the
/// operator named no `--p2p-listen`.
///
/// **Loopback, deliberately** (audit round 3, H-2). A swarm that binds every
/// interface is an exposure decision — firewall rules, the published bootnode
/// list, the fleet inventory all change with it — and a decision like that is
/// made by the operator typing `--p2p-listen /ip4/0.0.0.0/tcp/16400`, never by
/// a compiled-in default that a rebuild silently turns on. Loopback keeps the
/// swarm reachable for local tooling and for `dual` experiments on one box
/// while exposing nothing.
const DEFAULT_P2P_LISTEN: &str = "/ip4/127.0.0.1/tcp/16400";

/// What [`decide_transport`] decided: the transport, the listener settings
/// that follow from it, and the line the node prints about it.
///
/// This is the whole output of the decision. `run_cmd` copies these fields
/// into [`engine::Config`] and does not re-derive any of them, so the line
/// printed at boot and the sockets actually opened cannot disagree.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct TransportPlan {
    pub transport: engine::Transport,
    /// Devnet mesh port. `0` exactly when the plan runs no devnet mesh.
    pub listen: u16,
    /// libp2p listen multiaddrs, defaulted to [`DEFAULT_P2P_LISTEN`] when the
    /// plan runs a swarm and none was given. Empty exactly when the plan runs
    /// no swarm.
    pub p2p_listen: Vec<String>,
    /// One line, printed as `transport: <summary>`, naming the transport
    /// actually in effect and what it binds.
    pub summary: String,
    /// Flags that are real but that this transport does not read. Printed,
    /// never dropped in silence — see the note below on refused vs. warned.
    pub warnings: Vec<String>,
}

/// Decide the transport from the command line. **Pure**: it reads `args` and
/// nothing else — no clock, no filesystem, no environment, no `exit`, no
/// print — so every posture and every refusal below is a unit test.
///
/// # The default is Dual (flipped, deliberately)
///
/// `None => Dual`. The earlier default was `Devnet`, kept there because a node
/// that quietly came up on libp2p ALONE would find no peers and fork off. Dual
/// removes that hazard while opening the network: it runs the devnet TCP mesh
/// (so a node restarting with an unchanged unit file still finds the fleet) AND
/// binds a libp2p swarm (so an unaffiliated third party can dial in). Explicit
/// `--transport devnet` still selects devnet-only for anyone who wants it. This
/// flip is a fleet-wide decision and was made deliberately, not as cleanup.
///
/// # What is new is that the decision is stated, and contradictions refuse
///
/// Two failure modes are being closed:
///
///   1. **Silence.** The transport was an unannounced default. An operator
///      reading a node's log could not tell which network layer it was on.
///      Every plan now carries a `summary` and `run_cmd` prints it before a
///      socket is bound.
///   2. **Flags that did nothing.** `--p2p-listen` with the devnet transport
///      parsed fine and was then dropped on the floor, so the command line
///      said "I am on libp2p" and the process was not. Those combinations are
///      refused.
///
/// # Refused vs. warned
///
/// Refused: a flag naming a **listener or a peer** for a stack this plan does
/// not run. That is the class that makes an operator believe the node is
/// reachable somewhere it is not, and reachability is what a fleet is
/// debugged by.
///
/// Warned, not refused: `--max-peers` and `--behind-proxy`, which only *tune*
/// the swarm. They are routinely carried along in deployment templates that
/// predate a transport change, and refusing to boot a validator over a tuning
/// knob it does not read would trade a real outage for a cosmetic one.
pub(crate) fn decide_transport(args: &[String]) -> Result<TransportPlan, String> {
    let transport = match arg_value(args, "--transport").as_deref() {
        // Unchanged, and load-bearing: see the section above. `None` IS
        // `Devnet`: it is what `--help`, `net.rs`, the README, the bootnode
        // verifier (`deploy/bootnodes/verify-bootnodes.sh`) and the refusal
        // messages below all say, and what every unit file on the live fleet
        // was written against. A revision briefly mapped `None` to `Dual`
        // while leaving all of those documents saying devnet; every rebuilt
        // node then opened an all-interfaces libp2p listener that nobody had
        // asked for (audit round 3, H-2). Moving the fleet to `dual` is a
        // runbook change — an explicit `--transport dual --p2p-listen ...` in
        // the unit file, rolled host by host — not a silent compiled-in flip.
        None | Some("devnet") => engine::Transport::Devnet,
        Some("libp2p") => engine::Transport::Libp2p,
        // Dual is reachable ONLY by naming it.
        Some("dual") => engine::Transport::Dual,
        Some(other) => {
            return Err(format!(
                "--transport must be `devnet`, `libp2p` or `dual`, not `{other}`"
            ))
        }
    };
    let named = arg_value(args, "--transport").is_some();
    let runs_devnet = matches!(
        transport,
        engine::Transport::Devnet | engine::Transport::Dual
    );
    let runs_libp2p = matches!(
        transport,
        engine::Transport::Libp2p | engine::Transport::Dual
    );

    let present = |name: &str| args.iter().any(|a| a == name);
    let mut contradictions: Vec<String> = Vec::new();
    if !runs_libp2p {
        for f in ["--p2p-listen", "--p2p-peer"] {
            if present(f) {
                contradictions.push(f.to_string());
            }
        }
    }
    if !runs_devnet {
        for f in ["--listen", "--listen-addr", "--peers"] {
            if present(f) {
                contradictions.push(f.to_string());
            }
        }
    }
    if !contradictions.is_empty() {
        // The message names both ways out, because both are legitimate: an
        // operator who meant the flags wants `dual`, and an operator who meant
        // the transport wants the flags gone.
        return Err(format!(
            "{} {} for the `{}` transport, which does not {}. \
             Either drop {} or run `--transport dual`, which binds both stacks{}.",
            contradictions.join(" and "),
            if contradictions.len() == 1 { "is set" } else { "are set" },
            transport_name(transport),
            if runs_devnet {
                "run a libp2p swarm"
            } else {
                "run a devnet mesh"
            },
            if contradictions.len() == 1 { "it" } else { "them" },
            if named {
                ""
            } else {
                " (no --transport was given, so this is the devnet default)"
            },
        ));
    }

    let mut warnings = Vec::new();
    if !runs_libp2p {
        for f in ["--max-peers", "--behind-proxy"] {
            if present(f) {
                warnings.push(format!(
                    "{f} tunes the libp2p swarm and the `{}` transport runs none — it is being ignored",
                    transport_name(transport)
                ));
            }
        }
    }

    // Devnet port. Refused rather than defaulted, on BOTH arms that run a
    // mesh. A `dual` node that came up with only its libp2p half bound would
    // look, in every log line and every RPC answer, exactly like a node
    // bridging two populations — while one of them could not reach it at all.
    // Half a dual node is worse than none.
    let listen = if runs_devnet {
        match arg_value(args, "--listen") {
            None => {
                return Err(format!(
                    "--listen <port> is required for the `{}` transport",
                    transport_name(transport)
                ))
            }
            // A malformed port is a refusal, not a silent fall back to 0 — the
            // same rule `--rpc-port` follows. Binding an ephemeral port is
            // never what an operator who typed a number meant, and a mesh
            // listening where nobody dials is a node that is up and alone.
            Some(s) => match s.parse::<u16>() {
                Ok(0) | Err(_) => {
                    return Err(format!(
                        "--listen must be a port number 1-65535 (got `{s}`)"
                    ))
                }
                Ok(p) => p,
            },
        }
    } else {
        0
    };

    let mut p2p_listen: Vec<String> = arg_value(args, "--p2p-listen")
        .map(|s| {
            s.split(',')
                .filter(|p| !p.is_empty())
                .map(String::from)
                .collect()
        })
        .unwrap_or_default();
    if runs_libp2p && p2p_listen.is_empty() {
        p2p_listen.push(DEFAULT_P2P_LISTEN.to_string());
    }

    let listen_addr = arg_value(args, "--listen-addr").unwrap_or_else(|| "127.0.0.1".to_string());
    let summary = match transport {
        engine::Transport::Devnet => format!(
            "DEVNET{} — unauthenticated TCP mesh on {listen_addr}:{listen}, no libp2p swarm",
            if named {
                ""
            } else {
                " (default: no --transport given)"
            }
        ),
        engine::Transport::Libp2p => {
            format!("LIBP2P — swarm on {}, no devnet mesh", p2p_listen.join(", "))
        }
        engine::Transport::Dual => format!(
            "DUAL — devnet mesh on {listen_addr}:{listen} AND libp2p swarm on {}, both live in one process",
            p2p_listen.join(", ")
        ),
    };

    Ok(TransportPlan {
        transport,
        listen,
        p2p_listen,
        summary,
        warnings,
    })
}

/// The `--transport` spelling of an [`engine::Transport`], so a refusal names
/// the value the operator would have to type.
fn transport_name(t: engine::Transport) -> &'static str {
    match t {
        engine::Transport::Devnet => "devnet",
        engine::Transport::Libp2p => "libp2p",
        engine::Transport::Dual => "dual",
    }
}

fn run_cmd(args: &[String]) {
    self_check();
    let (Some(data_dir), Some(genesis_path)) =
        (arg_value(args, "--data-dir"), arg_value(args, "--genesis"))
    else {
        eprintln!("run: --data-dir and --genesis are required");
        exit(2);
    };
    // Two tiny, self-contained operator-override flags — engine.rs reads
    // the env var either way, so a flag here is sugar over it and nothing
    // downstream needs a second code path. SAFETY: single-threaded at this
    // point in startup, well before any thread that could race a read.
    // R3 M-1: lifts the finality-rewind ratchet — see `Engine::run`'s own
    // doc on `BLOCH_ALLOW_FINALITY_REWIND` for what this actually does.
    if args.iter().any(|a| a == "--allow-finality-rewind") {
        unsafe { std::env::set_var("BLOCH_ALLOW_FINALITY_REWIND", "1") };
    }
    // R6 HIGH-8: disables doppelgänger protection — see `Engine::run`'s doc
    // on `BLOCH_NO_DOPPELGANGER`.
    if args.iter().any(|a| a == "--no-doppelganger-check") {
        unsafe { std::env::set_var("BLOCH_NO_DOPPELGANGER", "1") };
    }
    // The transport is decided by a pure function (`decide_transport`) and
    // then ANNOUNCED. Nothing below re-derives it, and nothing silently drops
    // a flag: what the operator asked for either becomes the plan or becomes
    // a refusal with a reason.
    let plan = match decide_transport(args) {
        Ok(plan) => plan,
        Err(e) => {
            eprintln!("run: {e}");
            exit(2);
        }
    };
    // ONE LINE, NAMING THE TRANSPORT ACTUALLY IN EFFECT, BEFORE ANYTHING BINDS.
    //
    // The transport used to be a silent default: `--transport` absent meant
    // devnet and the log never said so, which is how a libp2p node could run
    // for a whole session "applying" and "finalizing" its own fork while its
    // operator believed it was on Bloch. A node states which network layer it
    // is on, in one greppable line, at the top of its log.
    println!("transport: {}", plan.summary);
    for w in &plan.warnings {
        eprintln!("transport: WARNING {w}");
    }
    let transport = plan.transport;
    let listen = plan.listen;
    let p2p_listen = plan.p2p_listen.clone();
    let csv = |name: &str| -> Vec<String> {
        arg_value(args, name)
            .map(|s| {
                s.split(',')
                    .filter(|p| !p.is_empty())
                    .map(String::from)
                    .collect()
            })
            .unwrap_or_default()
    };
    let stop_at_slot = arg_value(args, "--stop-at-slot").and_then(|s| s.parse::<u64>().ok());

    let ws = ws_boot::WsConfig {
        checkpoint: arg_value(args, "--ws-checkpoint").map(PathBuf::from),
        signer_set: arg_value(args, "--ws-signer-set").map(PathBuf::from),
    };

    // RPC. A malformed --rpc-port is refused rather than silently falling back
    // to the default: an operator who typed a port meant that port, and a node
    // listening somewhere else is worse than one that did not start.
    let rpc_port = match arg_value(args, "--rpc-port") {
        None => Some(DEFAULT_RPC_PORT),
        Some(s) if s == "off" || s == "0" => None,
        Some(s) => match s.parse::<u16>() {
            Ok(p) => Some(p),
            Err(_) => {
                eprintln!("run: --rpc-port must be a port number 1-65535, or `off` (got `{s}`)");
                exit(2);
            }
        },
    };

    // Metrics/health (audit C-R6-2). OPT-IN: no flag, no listener, so an
    // unflagged fleet binary behaves byte-for-byte as before. Same refusal
    // rule as --rpc-port: a malformed port stops the boot rather than
    // silently running unobserved — which is the exact failure mode this
    // endpoint exists to end.
    let metrics_port = match arg_value(args, "--metrics-port") {
        None => None,
        Some(s) if s == "off" || s == "0" => None,
        Some(s) => match s.parse::<u16>() {
            Ok(p) => Some(p),
            Err(_) => {
                eprintln!("run: --metrics-port must be a port number 1-65535, or `off` (got `{s}`)");
                exit(2);
            }
        },
    };

    let cfg = engine::Config {
        data_dir: PathBuf::from(data_dir),
        genesis_path: PathBuf::from(genesis_path),
        transport,
        listen,
        // Loopback unless asked otherwise: the devnet transport authenticates
        // nothing, so a routable bind is a deliberate act plus a firewall.
        listen_addr: arg_value(args, "--listen-addr").unwrap_or_else(|| "127.0.0.1".to_string()),
        peers: csv("--peers"),
        p2p_listen,
        p2p_peers: csv("--p2p-peer"),
        max_peers: arg_value(args, "--max-peers")
            .and_then(|s| s.parse().ok())
            .unwrap_or(64),
        behind_proxy: args.iter().any(|a| a == "--behind-proxy"),
        stop_at_slot,
        ws,
        // Required exactly when the manifest commits to a carryover; `run`
        // refuses both mismatches rather than defaulting either way.
        carryover_path: arg_value(args, "--carryover").map(PathBuf::from),
        // Loopback unless asked otherwise, for the same reason as the mesh
        // listener and one more: the RPC accepts `sendrawtransaction`, so an
        // exposed port is a write surface, not only a read one.
        rpc_bind: arg_value(args, "--rpc-bind").unwrap_or_else(|| "127.0.0.1".to_string()),
        rpc_port,
        // Loopback unless asked otherwise, like the RPC: /metrics is
        // read-only but still maps the node's peers, lag and validator
        // status for anyone who can reach it.
        metrics_bind: arg_value(args, "--metrics-bind").unwrap_or_else(|| "127.0.0.1".to_string()),
        metrics_port,
    };
    if let Err(e) = engine::run(cfg) {
        eprintln!("bloch-pos: {e}");
        exit(1);
    }
}

/// Sanity over the constants this binary stakes consensus on. Each assert
/// names the document that makes it an invariant.
fn self_check() {
    // §6.1 of the migration design: every hash use tagged, no two tags equal.
    let tags: [(&str, [u8; 16]); 10] = [
        ("DS_BLOCK", DS_BLOCK),
        ("DS_BODY", DS_BODY),
        ("DS_STATE", DS_STATE),
        ("DS_ATTEST", DS_ATTEST),
        ("DS_RANDAO", DS_RANDAO),
        ("DS_SORTITION", DS_SORTITION),
        ("DS_DEPOSIT", DS_DEPOSIT),
        ("DS_SLASH", DS_SLASH),
        ("DS_PROPOSE", DS_PROPOSE),
        ("DS_EXIT", DS_EXIT),
    ];
    for (i, (na, ta)) in tags.iter().enumerate() {
        assert!(
            ta.starts_with(b"BLCH4:"),
            "{na}: domain tag outside the BLCH4 namespace"
        );
        for (nb, tb) in tags.iter().skip(i + 1) {
            assert_ne!(ta, tb, "domain tags {na} and {nb} collide");
        }
    }

    // BLOCH-TOKENOMICS-V4 §8.1, both directions, as the crate pins them.
    //
    // This check used to read `TOTAL_SUPPLY_SAT < u64::MAX / 4` with the
    // comment "21 B at 8 decimals sits far below u64 wrap". That was a
    // restated number, and the 2026-08-12 pure ×100/21 split moved the supply
    // to 100 B — deliberately past u64's halfway point, with the headroom
    // loss accepted and pinned in `tokenomics_v4.rs`. The stale bound then
    // panicked on every `bloch-pos run` and `selfcheck`. Assert the invariant
    // the authority states, never a threshold chosen here: a single balance
    // must still fit the committed u64 columns, and the supply being past the
    // halfway point is what forces every satoshi *sum* to be u128.
    assert!(
        TOTAL_SUPPLY_SAT <= u64::MAX as u128,
        "a single balance no longer fits the u64 columns the state root commits"
    );
    assert!(
        TOTAL_SUPPLY_SAT * 2 > u64::MAX as u128,
        "supply left the u64 wrap zone — re-decide the accumulator widths on purpose"
    );
    // §1: validators get more than any single insider bucket. Compared
    // against the buckets themselves, so a re-split cannot make this pass by
    // arithmetic drift.
    assert!(
        VALIDATOR_EMISSION_BLOCH > FOUNDER_BLOCH
            && VALIDATOR_EMISSION_BLOCH > VC_BLOCH
            && VALIDATOR_EMISSION_BLOCH > TEAM_BLOCH,
        "validator allocation fell below an insider bucket"
    );

    // BLOCH-TOKENOMICS-V4 §3.3.1: cohort cap 100% → 33.33%, held after.
    assert_eq!(cohort_cap_bps(0), COHORT_CAP_START_BPS);
    assert_eq!(cohort_cap_bps(COHORT_TAPER_EPOCHS), COHORT_CAP_FLOOR_BPS);
    assert_eq!(
        cohort_cap_bps(10 * COHORT_TAPER_EPOCHS),
        COHORT_CAP_FLOOR_BPS
    );

    // Migration design §5.1: the slot cadence everything descends from.
    assert_eq!(SLOT_DURATION_SECS, 30);
    assert_eq!(SLOTS_PER_EPOCH, 32);

    // WIRE-NAMESPACE-REGISTRY.md §2 — the frame-byte namespace, and §7 gap 1,
    // which records that nothing froze it.
    //
    // This is the one shared namespace in the tree with NO compiler
    // diagnostic of any kind: `net.rs` matches `&FRAME_BLOCK` as a
    // binding-by-reference (so `unreachable_patterns` never fires) and
    // compares `FRAME_GET_BLOCKS` with a runtime `==`. Two constants with
    // different names and the same value are invisible to the toolchain. Five
    // collisions in this family were found in a single day in August 2026.
    //
    // Asserted here, at every `run`, and not only in a unit test, because the
    // failure it guards is a chain split and the cost of the check is four
    // comparisons at boot.
    let frames: [(&str, u8); 4] = [
        ("FRAME_BLOCK", net::FRAME_BLOCK),
        ("FRAME_ATT", net::FRAME_ATT),
        ("FRAME_GET_BLOCKS", net::FRAME_GET_BLOCKS),
        ("FRAME_TX", net::FRAME_TX),
    ];
    for (i, (na, a)) in frames.iter().enumerate() {
        assert_eq!(
            *a,
            (i + 1) as u8,
            "{na} is not on its registered allocation (§2 of the wire namespace registry)"
        );
        for (nb, b) in frames.iter().skip(i + 1) {
            assert_ne!(a, b, "frame bytes {na} and {nb} collide — silent chain split");
        }
    }
}

#[cfg(test)]
mod transport_tests {
    use super::*;

    fn argv(s: &str) -> Vec<String> {
        s.split_whitespace().map(String::from).collect()
    }

    /// **The default is devnet, and this test is what says so.**
    ///
    /// The live Genesis-4 fleet runs the devnet mesh and every document in the
    /// tree says so. A revision flipped the `None` arm to `Dual` without
    /// touching any of them, so every node rebuilt from it bound an
    /// all-interfaces libp2p listener that no operator had configured a
    /// firewall for (audit round 3, H-2). This test pins the documented
    /// default; a deliberate move to `dual` changes the unit files, this
    /// test, `--help`, `net.rs` and the bootnode verifier together, in one
    /// reviewed change.
    #[test]
    fn no_transport_flag_means_devnet() {
        let plan = decide_transport(&argv("--listen 16400")).expect("plan");
        assert_eq!(plan.transport, engine::Transport::Devnet);
        assert_eq!(plan.listen, 16400);
        assert!(plan.p2p_listen.is_empty(), "the default binds no swarm");
        assert!(
            plan.summary.contains("default"),
            "the line must say the transport was defaulted, not chosen: {}",
            plan.summary
        );
    }

    /// `--transport devnet` and no flag reach the same transport, and the only
    /// difference is that one line says it was chosen.
    #[test]
    fn naming_devnet_matches_the_default() {
        let implicit = decide_transport(&argv("--listen 16400")).unwrap();
        let explicit = decide_transport(&argv("--transport devnet --listen 16400")).unwrap();
        assert_eq!(implicit.transport, explicit.transport);
        assert_eq!(implicit.listen, explicit.listen);
        assert_eq!(implicit.p2p_listen, explicit.p2p_listen);
        assert!(!explicit.summary.contains("default"));
    }

    /// The compiled-in swarm address is loopback (H-2). An all-interfaces
    /// swarm is typed by the operator, never defaulted.
    #[test]
    fn the_default_swarm_address_is_loopback() {
        assert!(
            DEFAULT_P2P_LISTEN.starts_with("/ip4/127.0.0.1/"),
            "H-2: the default libp2p listener must be loopback, got {DEFAULT_P2P_LISTEN}"
        );
        let plan = decide_transport(&argv("--transport libp2p")).unwrap();
        assert_eq!(plan.p2p_listen, vec![DEFAULT_P2P_LISTEN.to_string()]);
        let named = decide_transport(&argv("--transport libp2p --p2p-listen /ip4/0.0.0.0/tcp/16400")).unwrap();
        assert_eq!(named.p2p_listen, vec!["/ip4/0.0.0.0/tcp/16400".to_string()]);
    }

    #[test]
    fn libp2p_binds_a_swarm_and_no_mesh() {
        let plan = decide_transport(&argv("--transport libp2p")).unwrap();
        assert_eq!(plan.transport, engine::Transport::Libp2p);
        assert_eq!(plan.listen, 0, "no devnet mesh means no devnet port");
        assert_eq!(plan.p2p_listen, vec![DEFAULT_P2P_LISTEN.to_string()]);
        assert!(plan.summary.contains("LIBP2P"));
    }

    /// The posture this whole change exists for: one process, both stacks.
    #[test]
    fn dual_binds_both_stacks() {
        let plan = decide_transport(&argv(
            "--transport dual --listen 16400 --p2p-listen /ip4/0.0.0.0/tcp/16500",
        ))
        .unwrap();
        assert_eq!(plan.transport, engine::Transport::Dual);
        assert_eq!(plan.listen, 16400);
        assert_eq!(plan.p2p_listen, vec!["/ip4/0.0.0.0/tcp/16500".to_string()]);
        assert!(plan.summary.contains("DUAL"));
        assert!(plan.summary.contains("16400") && plan.summary.contains("16500"));
    }

    /// A dual node with no `--p2p-listen` still binds a swarm, on the same
    /// default a libp2p-only node would use — half a dual node is not a
    /// posture this function can produce.
    #[test]
    fn dual_defaults_the_swarm_address() {
        let plan = decide_transport(&argv("--transport dual --listen 16400")).unwrap();
        assert_eq!(plan.p2p_listen, vec![DEFAULT_P2P_LISTEN.to_string()]);
    }

    /// The flags that used to be parsed and silently dropped.
    #[test]
    fn devnet_refuses_libp2p_listener_flags() {
        for line in [
            "--transport devnet --listen 16400 --p2p-listen /ip4/0.0.0.0/tcp/16500",
            "--transport devnet --listen 16400 --p2p-peer /ip4/1.2.3.4/tcp/16500",
            // Under the DEFAULT too: no --transport is devnet, so a libp2p
            // flag there is the same mistake, and the refusal must say the
            // default was taken so the operator knows what to type.
            "--listen 16400 --p2p-listen /ip4/0.0.0.0/tcp/16500",
        ] {
            let e = decide_transport(&argv(line)).expect_err(line);
            assert!(e.contains("dual"), "the refusal must name the way out: {e}");
            if !line.contains("--transport") {
                assert!(e.contains("devnet default"), "{e}");
            }
        }
    }

    #[test]
    fn libp2p_refuses_devnet_listener_flags() {
        for line in [
            "--transport libp2p --listen 16400",
            "--transport libp2p --listen-addr 0.0.0.0",
            "--transport libp2p --peers 1.2.3.4:16400",
        ] {
            let e = decide_transport(&argv(line)).expect_err(line);
            assert!(e.contains("dual"), "{e}");
        }
    }

    /// Dual accepts both halves' flags — that is the definition of the
    /// posture, and the refusals above must not reach it.
    #[test]
    fn dual_accepts_both_halves_flags() {
        decide_transport(&argv(
            "--transport dual --listen 16400 --listen-addr 0.0.0.0 --peers 1.2.3.4:16400 \
             --p2p-listen /ip4/0.0.0.0/tcp/16500 --p2p-peer /ip4/5.6.7.8/tcp/16500 \
             --max-peers 64 --behind-proxy",
        ))
        .expect("dual is the posture that reads every one of these");
    }

    /// Tuning knobs warn instead of refusing: a deployment template that
    /// carries `--behind-proxy` across a transport change must not turn into a
    /// validator that will not boot.
    #[test]
    fn devnet_warns_but_boots_with_swarm_tuning_flags() {
        let plan = decide_transport(&argv("--transport devnet --listen 16400 --max-peers 32 --behind-proxy")).unwrap();
        assert_eq!(plan.transport, engine::Transport::Devnet);
        assert_eq!(plan.warnings.len(), 2, "{:?}", plan.warnings);
        assert!(plan.warnings.iter().any(|w| w.contains("--max-peers")));
        assert!(plan.warnings.iter().any(|w| w.contains("--behind-proxy")));
    }

    #[test]
    fn a_mesh_without_a_port_is_refused_on_both_arms() {
        assert!(decide_transport(&argv("--transport devnet")).is_err());
        assert!(decide_transport(&argv("--transport dual")).is_err());
        // And a port that is not a port, rather than a silent bind to an
        // ephemeral one nobody will dial.
        assert!(decide_transport(&argv("--listen banana")).is_err());
        assert!(decide_transport(&argv("--listen 0")).is_err());
        assert!(decide_transport(&argv("--listen 99999")).is_err());
    }

    #[test]
    fn an_unknown_transport_names_all_three() {
        let e = decide_transport(&argv("--transport quic --listen 16400")).unwrap_err();
        assert!(
            e.contains("devnet") && e.contains("libp2p") && e.contains("dual"),
            "{e}"
        );
    }

    /// Every plan says which transport it is, in a line an operator can grep a
    /// fleet's logs for.
    #[test]
    fn every_posture_announces_itself() {
        for (line, want) in [
            ("--listen 16400", "DEVNET"),
            ("--transport devnet --listen 16400", "DEVNET"),
            ("--transport libp2p", "LIBP2P"),
            ("--transport dual --listen 16400", "DUAL"),
        ] {
            let plan = decide_transport(&argv(line)).unwrap();
            assert!(plan.summary.contains(want), "{line} → {}", plan.summary);
        }
    }
}
