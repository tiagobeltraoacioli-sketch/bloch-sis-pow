//! # bloch-pos — the Genesis-4 node binary
//!
//! This binary runs the live proof-of-stake mainnet. It called itself a
//! devnet-stage build until 2026-08-14 — which was true when written and
//! false the moment Genesis-4 launched, and it was the first line anyone
//! evaluating the software read.
//!
//! From the skeleton this grew into a node that actually runs: a devnet of N
//! validator processes produces blocks, attests, justifies and finalizes over
//! a local TCP mesh, with real ML-DSA-65 ‖ Falcon-1024 hybrid signatures and
//! append-only block-log persistence (restart = deterministic replay).
//!
//! Since 2026-08-13 it also has a production network layer (`p2p`): libp2p +
//! gossipsub on Genesis-4-only protocol ids, carrying the Genesis-3 mesh
//! fixes, with `gossip.rs` wired as attestation admission control and a
//! directed, paginated block-sync path. A node started with an **empty data
//! dir** syncs from genesis and validates every block itself — no datadir is
//! ever donated. `--transport devnet` keeps the original TCP mesh, and is
//! still the default.
//!
//! What it is NOT yet — honestly, per the integration plan
//! (`docs/specs/BLOCH-POS-NODE-INTEGRATION.md`): no RocksDB store, no
//! post-quantum transport handshake (the p2p layer uses Noise; consensus
//! signatures are hybrid PQ regardless), no peer persistence or peer
//! exchange, no deposits/exits, no slashing-evidence pipeline, no
//! checkpoint-sync **state download** (the weak-subjectivity boot gate itself
//! IS wired — `ws_boot`). RPC and the mainnet genesis manifest were on this
//! list and have since been wired: `mod rpc` is served from the engine once the
//! boot gate clears, and `genesis-mainnet` is a subcommand of this binary. See
//! the module docs of `engine`, `net`, `p2p`, `rpc`, `store`, `ws_boot` for
//! each limitation at its site.
//!
//! ## Key hygiene
//!
//! `keygen` produces **throwaway devnet keys only** (never printed, 0600
//! files). Production keys are generated by a human on an air-gapped machine
//! per BLOCH-GENESIS-KEYS.md rule zero — never by this tool in an observable
//! session.
//!
//! ## Ownership
//!
//! `main.rs` is the composition root (PMO change-controlled; §9.4 two-reviewer
//! rule once integration review starts).

