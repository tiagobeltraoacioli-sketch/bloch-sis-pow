/// Default JSON-RPC port. Deliberately NOT the Genesis-3 node's 16210: the
/// migration plan keeps a G3 archive node serving the frozen V3 surface, and
/// the two are expected to run on the same host during the changeover. Sharing
/// a port would mean whichever bound first silently answered for the other
/// chain — a client asking a V4 node for `getblockcount` and getting a PoW
/// height is the kind of confusion that ends in a miscredited deposit.
const DEFAULT_RPC_PORT: u16 = 16310;
/// `pkg-version (git-commit[+dirty])`, stamped by build.rs. The commit is the
/// load-bearing part: the G8 release-integrity gate compares fleet, release
/// and source through it (deploy/RELEASE-INTEGRITY.md). Never fall back to
/// bare CARGO_PKG_VERSION — three identical "0.3.0-genesis2" strings on three
/// different binaries is the exact failure this replaces.
const VERSION: &str = env!("BLOCH_BUILD_VERSION");

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    // Audit I-H1. The keystore is sealed (Argon2id + XChaCha20-Poly1305) and
    // its passphrase comes from BLOCH_KEYSTORE_PASSPHRASE_FILE /
    // BLOCH_KEYSTORE_PASSPHRASE. Reading or writing a PLAINTEXT keystore is
    // possible only when the operator says so here, once, for the whole
    // process — never inferred from the file that happened to be on disk.
    // Applies to `run`, `keygen` and `keygen-public` alike, which is why it is
    // read before the subcommand dispatch rather than inside one of them.
    if args.iter().any(|a| a == "--allow-plaintext-keystore") {
        keys::allow_plaintext_at_rest();
    }
    match args.first().map(String::as_str) {
        Some("--version") | Some("-V") => {
            println!(
                "{NAME} {VERSION} (Genesis-4, block version {:#010x})",
                bloch_pos_committee::header::VERSION_G4
            );
            // Second line, appended rather than folded into the first, because
            // `scripts/pos-release-integrity.sh` and the fleet sweep in
            // deploy/RELEASE-INTEGRITY.md match the first line's shape.
            //
            // The commit answers "what was checked out"; the digest answers
            // "what was compiled", and only the second one survives an
            // operator editing a file and rebuilding. See `rpc::build_info_json`
            // for what each field can and cannot prove.
            println!(
                "source-digest sha3-256:{} ({} files, {} bytes) commit-source:{} tree:{}",
                env!("BLOCH_SOURCE_DIGEST"),
                env!("BLOCH_SOURCE_FILES"),
                env!("BLOCH_SOURCE_BYTES"),
                env!("BLOCH_BUILD_COMMIT_SOURCE"),
                env!("BLOCH_BUILD_TREE_STATE"),
            );
        }
        // The same object `getbuildinfo` returns, for an operator who is on the
        // box and for a release check that must compare two artifacts without
        // standing either of them up as a node.
        Some("buildinfo") => println!("{}", rpc::build_info_json().to_string()),
        Some("--help") | Some("-h") | None => print_help(),
        Some("selfcheck") => {
            self_check();
            println!("self-check passed");
        }
        Some("keygen") => keygen(&args[1..]),
        Some("keygen-public") => keygen_public(&args[1..]),
        Some("keys") => keys_cmd(&args[1..]),
        Some("genesis") => genesis_cmd(&args[1..]),
        Some("genesis-mainnet") => genesis_mainnet(&args[1..]),
        Some("submit-tx") => submit_tx(&args[1..]),
        Some("run") => run_cmd(&args[1..]),
        Some(other) => {
            eprintln!("{NAME}: unknown command `{other}` (see --help)");
            exit(2);
        }
    }
}

