/// Default JSON-RPC port. Deliberately NOT the Genesis-3 node's 16210: the
/// migration plan keeps a G3 archive node serving the frozen V3 surface, and
/// the two are expected to run on the same host during the changeover. Sharing
/// a port would mean whichever bound first silently answered for the other
/// chain — a client asking a V4 node for `getblockcount` and getting a PoW
/// height is the kind of confusion that ends in a miscredited deposit.
const DEFAULT_RPC_PORT: u16 = 16310;
/// `pkg-version (git-commit[+dirty])`, stamped by build.rs. The commit is the
/// load-bearing part: the G8 release-integrity gate compares fleet, release
/// and source through it (deploy/RELEASE-INTEGRITY.md). Never fall back to
/// bare CARGO_PKG_VERSION — three identical "0.3.0-genesis2" strings on three
/// different binaries is the exact failure this replaces.
const VERSION: &str = env!("BLOCH_BUILD_VERSION");

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("--version") | Some("-V") => {
            println!(
                "{NAME} {VERSION} (Genesis-4, block version {:#010x})",
                bloch_pos_committee::header::VERSION_G4
            );
        }
        Some("--help") | Some("-h") | None => print_help(),
        Some("selfcheck") => {
            self_check();
            if args.iter().any(|a| a == "--json") {
                println!("{}", consensus_compat_json());
            } else {
                println!("self-check passed");
                print_consensus_compat();
            }
        }
        Some("keygen") => keygen(&args[1..]),
        Some("keygen-public") => keygen_public(&args[1..]),
        Some("genesis") => genesis_cmd(&args[1..]),
        Some("genesis-mainnet") => genesis_mainnet(&args[1..]),
        Some("submit-tx") => submit_tx(&args[1..]),
        Some("spendkey") => spendkey(&args[1..]),
        Some("protection-export") => protection_export(&args[1..]),
        Some("protection-import") => protection_import(&args[1..]),
        // Two names, one command: `doctor` is what an operator types when
        // something is wrong, `preflight` is what a runbook says before a
        // first start. Refusing one of them to keep a table small helps
        // nobody at 3am.
        Some("doctor") | Some("preflight") => {
            if args.iter().any(|a| a == "--help" || a == "-h") {
                doctor::print_help();
            } else {
                exit(doctor::run(&args[1..]));
            }
        }
        Some("run") => run_cmd(&args[1..]),
        Some(
            cmd @ ("ws-keygen" | "ws-signer-set" | "ws-checkpoint" | "ws-sign" | "ws-envelope"
            | "ws-verify"),
        ) => ws_tool::run(cmd, &args[1..]),
        Some(other) => {
            eprintln!("{NAME}: unknown command `{other}` (see --help)");
            exit(2);
        }
    }
}

