"""Fresh build context for qualification builds (BRIEF rule: never a cached context).

  fresh-build.py engine --engine <container engine> --out <file>
      Writes a wrapper engine. Before every `buildx build` it drops the
      builder's synced local contexts (`buildx prune -f --filter
      type=source.local`, errors ignored), then runs the build with
      --no-cache. Every other command passes through unchanged.

  fresh-build.py check --log <buildkit plain-progress log> --min-context-bytes N
                       [--no-context-floor]
      Refuses a build that reused a cache:
        - any RUN, COPY or ADD step reported CACHED (a cached compile or a
          cached copy of the source);
        - the build context ("[internal] load build context") transferred
          fewer than N bytes (N = the source-digest scope of the tree, so every
          hashed file must have crossed into the builder; an incremental
          transfer that reused an older copy of the context is refused);
        - no build context step at all (nothing proves the source was sent).
      A log may hold several builds; each one is checked. --no-context-floor
      keeps only the CACHED rule (for a second build that reuses the context
      of the first one in the same run).
      Prints "PASS <summary>" (exit 0) or "FAIL <reason>" (exit 1).

Why both rules: the 78d4921c forced build of 2026-10-25 compiled (its cargo
step was not CACHED) but transferred a 79.74 kB context, so the compile saw the
unpatched params.rs and the binary reported the release source-digest. A later
canonical build transferred the whole 53.87 MB context but every RUN step was
CACHED. Each rule alone misses one of the two.
"""
import argparse
import os
import re
import shlex
import stat
import sys

STEP = re.compile(r"^#(\d+) (.*)$")
SIZE = re.compile(r"transferring context: ([0-9.]+)\s*([kMG]?B)\b")
UNITS = {"B": 1, "kB": 1000, "MB": 1000 ** 2, "GB": 1000 ** 3}
SOURCE_STEP = re.compile(r"^\[[^\]]+\] (RUN|COPY|ADD)\b")
STATUS = re.compile(r"^(CACHED|DONE\b|ERROR\b|CANCELED\b|transferring\b|resolve\b|sha256:|extracting\b|"
                    r"writing\b|naming\b|exporting\b|copying\b|unpacking\b|preparing\b|sending\b|"
                    r"[0-9]+\.[0-9]+ )")


def parse(lines):
    """Split a plain-progress log into builds; each build maps step id -> record."""
    builds, cur = [], None
    for raw in lines:
        m = STEP.match(raw.rstrip("\n"))
        if not m:
            continue
        sid, text = int(m.group(1)), m.group(2)
        # A build starts at "#0 building with ..." (buildx) or, without that
        # line, at "#1 [internal] load build definition".
        starts = sid == 0 or (sid == 1 and text.startswith("[internal] load build definition")
                              and (cur is None or any(k >= 1 for k in cur)))
        if starts:
            cur = {}
            builds.append(cur)
        if cur is None:
            cur = {}
            builds.append(cur)
        rec = cur.setdefault(sid, {"header": None, "cached": False, "context": 0})
        if rec["header"] is None and not STATUS.match(text):
            rec["header"] = text
        if text == "CACHED":
            rec["cached"] = True
        s = SIZE.search(text)
        if s:
            rec["context"] = max(rec["context"], int(float(s.group(1)) * UNITS[s.group(2)]))
    return builds


def check(lines, floor, use_floor=True):
    builds = parse(lines)
    if not builds:
        return False, "no buildkit steps in the log (plain progress expected)"
    notes = []
    for n, steps in enumerate(builds, 1):
        cached = [r["header"] or f"step #{sid}" for sid, r in sorted(steps.items())
                  if r["cached"] and r["header"] and SOURCE_STEP.match(r["header"])]
        if cached:
            return False, f"build {n}: cached step(s) {'; '.join(h[:80] for h in cached)}"
        ctx = [r["context"] for r in steps.values()
               if (r["header"] or "").startswith("[internal] load build context")]
        if use_floor:
            if not ctx:
                return False, f"build {n}: no '[internal] load build context' step"
            if max(ctx) < floor:
                return False, (f"build {n}: build context transferred {max(ctx)} bytes, below the "
                               f"{floor}-byte source-digest scope (incremental transfer of an older context)")
        notes.append(f"build {n}: context {max(ctx) if ctx else 0} B, no cached RUN/COPY/ADD")
    return True, "; ".join(notes)


def write_engine(engine, out):
    body = "\n".join([
        "#!/usr/bin/env bash",
        "# Generated by fresh-build.py: every buildx build starts from a fresh context.",
        f"engine={shlex.quote(engine)}",
        'if [ "${1:-}" = buildx ] && [ "${2:-}" = build ]; then',
        "  shift 2",
        '  "$engine" buildx prune -f --filter type=source.local >/dev/null 2>&1 || true',
        '  exec "$engine" buildx build --no-cache "$@"',
        "fi",
        'exec "$engine" "$@"',
        "",
    ])
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(out, stat.S_IRWXU)


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("engine")
    e.add_argument("--engine", required=True)
    e.add_argument("--out", required=True)
    c = sub.add_parser("check")
    c.add_argument("--log", required=True)
    c.add_argument("--min-context-bytes", type=int, default=0)
    c.add_argument("--no-context-floor", action="store_true")
    a = p.parse_args()
    if a.cmd == "engine":
        write_engine(a.engine, a.out)
        return 0
    if not a.no_context_floor and a.min_context_bytes <= 0:
        p.error("--min-context-bytes must be positive (or give --no-context-floor)")
    with open(a.log, encoding="utf-8", errors="replace") as fh:
        ok, why = check(fh, a.min_context_bytes, not a.no_context_floor)
    print(("PASS " if ok else "FAIL ") + why)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
